package com.dsasummariser.service;

import com.dsasummariser.exception.TranscriptUnavailableException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;
import org.springframework.web.client.RestClient;

import java.net.URI;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Tests how we read YouTube's player JSON. No network: findCaptionUrl only looks at the JSON we pass in. */
class YoutubeTranscriptFetcherTest {

    private final ObjectMapper mapper = new ObjectMapper();
    private final YoutubeTranscriptFetcher fetcher =
            new YoutubeTranscriptFetcher(RestClient.builder(), new TranscriptParser());

    private JsonNode json(String s) throws Exception {
        return mapper.readTree(s);
    }

    private static String playerWithTracks(String tracks) {
        return "{\"playabilityStatus\":{\"status\":\"OK\"},\"captions\":{\"playerCaptionsTracklistRenderer\":{\"captionTracks\":["
                + tracks + "]}}}";
    }

    private static String track(String lang, boolean auto, String url) {
        return "{\"baseUrl\":\"" + url + "\",\"languageCode\":\"" + lang + "\""
                + (auto ? ",\"kind\":\"asr\"" : "") + "}";
    }

    @Test
    void prefersManualEnglishOverAutoGenerated() throws Exception {
        String tracks = track("en", true, "https://x/auto") + "," + track("en", false, "https://x/manual");
        assertEquals(URI.create("https://x/manual"), fetcher.findCaptionUrl(json(playerWithTracks(tracks))));
    }

    @Test
    void usesAutoEnglishWhenThereIsNoManualEnglish() throws Exception {
        // The manual Hindi track is ignored: only English is accepted.
        String tracks = track("hi", false, "https://x/hindi") + "," + track("en", true, "https://x/auto");
        assertEquals(URI.create("https://x/auto"), fetcher.findCaptionUrl(json(playerWithTracks(tracks))));
    }

    @Test
    void rejectsVideoWithOnlyNonEnglishTracks() throws Exception {
        String tracks = track("hi", true, "https://x/hindi-auto") + "," + track("de-DE", false, "https://x/german");
        var ex = assertThrows(TranscriptUnavailableException.class,
                () -> fetcher.findCaptionUrl(json(playerWithTracks(tracks))));
        assertTrue(ex.getMessage().contains("Only English captions are supported"));
        assertEquals("NO_ENGLISH_CAPTIONS", ex.getCode());
        assertTrue(ex.getMessage().contains("paste an English transcript"));
    }

    @Test
    void acceptsEnglishVariantsLikeEnUsAndEnGb() throws Exception {
        assertEquals(URI.create("https://x/us"),
                fetcher.findCaptionUrl(json(playerWithTracks(track("en-US", false, "https://x/us")))));
        assertEquals(URI.create("https://x/gb"),
                fetcher.findCaptionUrl(json(playerWithTracks(track("en-GB", true, "https://x/gb")))));
    }

    @Test
    void prefersManualEnglishVariantOverAutoPlainEnglish() throws Exception {
        String tracks = track("en", true, "https://x/auto") + "," + track("en-GB", false, "https://x/manual-gb");
        assertEquals(URI.create("https://x/manual-gb"), fetcher.findCaptionUrl(json(playerWithTracks(tracks))));
    }

    @Test
    void languageCodeMatchIsCaseInsensitive() throws Exception {
        assertEquals(URI.create("https://x/up"),
                fetcher.findCaptionUrl(json(playerWithTracks(track("EN-us", false, "https://x/up")))));
    }

    @Test
    void failsWhenVideoHasNoCaptions() throws Exception {
        var ex = assertThrows(TranscriptUnavailableException.class,
                () -> fetcher.findCaptionUrl(json("{\"playabilityStatus\":{\"status\":\"OK\"}}")));
        assertTrue(ex.getMessage().contains("no captions"));
        assertEquals("NO_CAPTIONS", ex.getCode());
    }

    @Test
    void passesThroughYoutubeReasonForPrivateOrRemovedVideos() throws Exception {
        var ex = assertThrows(TranscriptUnavailableException.class, () -> fetcher.findCaptionUrl(
                json("{\"playabilityStatus\":{\"status\":\"ERROR\",\"reason\":\"Video unavailable\"}}")));
        assertTrue(ex.getMessage().contains("Video unavailable"));
        assertEquals("VIDEO_UNAVAILABLE", ex.getCode());
    }
}
