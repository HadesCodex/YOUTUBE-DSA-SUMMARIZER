package com.dsasummariser;

import com.dsasummariser.exception.TranscriptUnavailableException;
import com.dsasummariser.service.TranscriptParser;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class TranscriptParserTest {

    private final TranscriptParser parser = new TranscriptParser();

    private static String wrap(String paragraphs) {
        return "<?xml version=\"1.0\" encoding=\"utf-8\" ?><timedtext format=\"3\"><body>" + paragraphs + "</body></timedtext>";
    }

    @Test
    void joinsSegmentsWithSingleSpaces() {
        String xml = wrap("<p t=\"0\" d=\"1000\">Today we study</p><p t=\"1000\" d=\"1000\">binary search</p>");
        assertEquals("Today we study binary search", parser.parse(xml));
    }

    @Test
    void decodesHtmlEntities() {
        String xml = wrap("<p t=\"0\" d=\"1\">we&#39;re using a &lt;b&gt; tree &amp; heap</p>");
        assertEquals("we're using a <b> tree & heap", parser.parse(xml));
    }

    @Test
    void decodesDoubleEncodedEntities() {
        String xml = wrap("<p t=\"0\" d=\"1\">it&amp;#39;s O(n)</p>");
        assertEquals("it's O(n)", parser.parse(xml));
    }

    @Test
    void collapsesNewlinesInsideSegments() {
        String xml = wrap("<p t=\"0\" d=\"1\">first line\nsecond   line</p>");
        assertEquals("first line second line", parser.parse(xml));
    }

    @Test
    void dropsSoundCuesAndEmptySegments() {
        String xml = wrap("<p t=\"0\" d=\"1\">[Music]</p><p t=\"1\" d=\"1\">hello [Applause] world</p><p t=\"2\" d=\"1\">  </p>");
        assertEquals("hello world", parser.parse(xml));
    }

    @Test
    void joinsNestedWordTagsFromAutoGeneratedCaptions() {
        String xml = wrap("<p t=\"0\" d=\"1\"><s>two</s><s> pointers</s></p>");
        assertEquals("two pointers", parser.parse(xml));
    }

    @Test
    void rejectsBlankInput() {
        assertThrows(TranscriptUnavailableException.class, () -> parser.parse("  "));
        assertThrows(TranscriptUnavailableException.class, () -> parser.parse(null));
    }

    @Test
    void rejectsTrackWithNoText() {
        assertThrows(TranscriptUnavailableException.class, () -> parser.parse(wrap("<p t=\"0\" d=\"1\">[Music]</p>")));
    }

    @Test
    void rejectsMalformedXml() {
        assertThrows(TranscriptUnavailableException.class, () -> parser.parse("<html>not xml"));
    }

    @Test
    void rejectsDoctypeToBlockXxe() {
        String evil = "<?xml version=\"1.0\"?><!DOCTYPE x [<!ENTITY e SYSTEM \"file:///etc/passwd\">]><timedtext><body><p>&e;</p></body></timedtext>";
        assertThrows(TranscriptUnavailableException.class, () -> parser.parse(evil));
    }
}
